// Conteúdo da Ajuda: regras que não podem quebrar (palavras, tamanhos, busca, mensagem do dia).
import { LICOES, PERGUNTAS, MENSAGENS_DO_DIA, mensagemDeHoje, saudacao, buscarPerguntas, hojeChave } from '../src/ajuda/conteudo.js';
let ok = 0, falhas = [];
const t = (c, m) => (c ? ok++ : falhas.push(m));
t(MENSAGENS_DO_DIA.length >= 30, 'há mensagens para um mês inteiro sem repetir');
t(new Set(MENSAGENS_DO_DIA).size === MENSAGENS_DO_DIA.length, 'nenhuma mensagem repetida');
t(MENSAGENS_DO_DIA.every((m) => m.length >= 40 && m.length <= 200), 'mensagens nem curtas demais nem longas demais para ler de uma vez');
t(MENSAGENS_DO_DIA.every((m) => !/maleta/i.test(m)), 'a palavra "maleta" não aparece nas mensagens');
const dias = Array.from({ length: 31 }, (_, i) => mensagemDeHoje(new Date(2026, 9, 1 + i)));
t(dias.every((m, i) => i === 0 || m !== dias[i - 1]), 'dois dias seguidos nunca têm a mesma mensagem');
t(new Set(dias).size === 31, '31 dias seguidos usam 31 mensagens diferentes');
t(mensagemDeHoje(new Date(2026, 9, 4, 8)) === mensagemDeHoje(new Date(2026, 9, 4, 22)), 'no mesmo dia a mensagem é a mesma (de manhã ou à noite)');
t(saudacao(new Date(2026, 9, 4, 8)) === 'Bom dia' && saudacao(new Date(2026, 9, 4, 14)) === 'Boa tarde' && saudacao(new Date(2026, 9, 4, 21)) === 'Boa noite', 'saudação muda com a hora');
t(hojeChave(new Date(2026, 0, 5)) === '2026-01-05', 'chave do dia no formato certo');
t(LICOES.length >= 7, 'há pelo menos 7 lições');
t(LICOES.every((l) => l.id && l.titulo && l.resumo && l.minutos > 0 && l.passos.length >= 3), 'toda lição tem título, resumo, tempo e ao menos 3 passos');
t(new Set(LICOES.map((l) => l.id)).size === LICOES.length, 'ids de lição únicos');
t(LICOES.every((l) => l.passos.every((p) => p.fala && p.detalhe && p.fala.length <= 70 && p.detalhe.length <= 230)), 'cada passo: instrução curta (≤70) e explicação curta (≤230)');
t(LICOES.every((l) => l.passos.every((p) => !p.alvo || (Array.isArray(p.alvo) && p.alvo.length))), 'alvos são listas de texto');
const todos = JSON.stringify([LICOES, PERGUNTAS, MENSAGENS_DO_DIA]);
t(!/maleta/i.test(todos), 'a palavra "maleta" não aparece em nenhuma lição, pergunta ou mensagem');
t(!/\b(OCR|RPC|API|slug|token|SQL|login)\b/i.test(todos), 'sem jargão técnico (OCR, API, slug, token…)');
const ids = new Set(LICOES.map((l) => l.id));
t(PERGUNTAS.every((p) => !p.licao || ids.has(p.licao)), 'toda pergunta aponta para uma lição que existe');
t(PERGUNTAS.every((p) => p.q && p.passos && p.passos.length >= 1), 'toda pergunta tem resposta em passos');
t(PERGUNTAS.some((p) => p.suporte), 'há pergunta que leva ao atendimento humano');
const top = (txt) => (buscarPerguntas(txt)[0] || {}).q || '';
t(/foto/i.test(top('foto')), 'buscar "foto" acha a pergunta de foto: ' + top('foto'));
t(/venda/i.test(top('como vender')), 'buscar "como vender" acha a de venda: ' + top('como vender'));
t(/Como mando a minha loja/i.test(top('mandar link whatsapp')), 'buscar "mandar link whatsapp" acha a da loja: ' + top('mandar link whatsapp'));
t(/depois/i.test(top('cliente vai pagar depois')), 'buscar "cliente vai pagar depois" acha a do fiado: ' + top('cliente vai pagar depois'));
t(buscarPerguntas('PRECO').length > 0 && buscarPerguntas('preço').length > 0, 'a busca ignora acento e maiúscula');
t(buscarPerguntas('').length === 0 && buscarPerguntas('a').length === 0, 'busca vazia ou de 1 letra não devolve nada');
t(buscarPerguntas('xyzqk').length === 0, 'busca sem relação não inventa resposta');
console.log(falhas.length ? `AJUDA (conteúdo): ${falhas.length} FALHA(S)\n- ` + falhas.join('\n- ') : `AJUDA (conteúdo) OK: ${ok} de ${ok}`);
process.exit(falhas.length ? 1 : 0);
